"""Code shared by the OpenCode and Kilo agents.

Kilo is a fork of OpenCode and reads the same config schema and plugin files, so the Databricks
auth plugin, the provider ids ug manages and the model and version checks are defined once here.
`opencode.py` and `kilo.py` call these functions and keep the values that tests patch (versions,
paths and tokens).

The auth prelude is built once at import from `PROVIDER_IDS`."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass

from ucode.databricks import build_auth_token_argv

# The providers ug writes into the config, and the ones the auth plugin refreshes tokens for.
PROVIDER_IDS = ("databricks-anthropic", "databricks-google", "databricks-oss")


def provider_keys() -> list[list[str]]:
    """Return the config key path of each managed provider."""
    return [["provider", provider_id] for provider_id in PROVIDER_IDS]


_PRELUDE_TEMPLATE = """// Generated by ucode. Keep Databricks auth fresh for model requests.
import { execFile } from "node:child_process"
import { promisify } from "node:util"

const DATABRICKS_PROVIDERS = new Set([
__PROVIDER_IDS__
])
const AUTH_COMMAND = __AUTH_COMMAND__
const REFRESH_SKEW_MS = 120_000
const run = promisify(execFile)

let accessToken
let expiresAt = 0
let refreshPromise

function cacheToken(value) {
  accessToken = value
  expiresAt = Infinity
  try {
    const claims = JSON.parse(Buffer.from(value.split(".")[1], "base64url").toString())
    if (typeof claims.exp === "number") expiresAt = claims.exp * 1000
  } catch {}
}

async function mintToken() {
  try {
    const { stdout } = await run(AUTH_COMMAND[0], AUTH_COMMAND.slice(1), { encoding: "utf8" })
    const token = stdout.trim()
    if (!token) throw new Error("returned an empty token")
    cacheToken(token)
  } catch (error) {
    const detail = String(error.stderr || error.message || "").trim()
    throw new Error("ug auth-token failed" + (detail ? ": " + detail : ""))
  }
}

function refreshToken() {
  if (!refreshPromise) refreshPromise = mintToken().finally(() => { refreshPromise = undefined })
  return refreshPromise
}
"""

# OpenCode 1.x calls each exported plugin function; its `config` hook installs
# a refreshing `fetch` on the managed providers.
_V1_ENTRYPOINT = """
function requestWithToken(input, init, token) {
  const headers = new Headers(input instanceof Request ? input.headers : undefined)
  new Headers(init?.headers).forEach((value, key) => headers.set(key, value))
  headers.set("Authorization", "Bearer " + token)
  return { ...init, headers }
}

async function databricksFetch(input, init) {
  if (!accessToken || expiresAt <= Date.now() + REFRESH_SKEW_MS) await refreshToken()
  const attemptedToken = accessToken
  const response = await fetch(input, requestWithToken(input, init, attemptedToken))
  if (response.status !== 401) return response

  // Another concurrent request may already have refreshed this token.
  if (accessToken === attemptedToken) await refreshToken()
  return fetch(input, requestWithToken(input, init, accessToken))
}

export const UcodeDatabricksAuth = async () => ({
  config: async (config) => {
    for (const providerID of DATABRICKS_PROVIDERS) {
      const options = config.provider?.[providerID]?.options
      if (!options) continue
      if (!accessToken && typeof options.apiKey === "string") cacheToken(options.apiKey)
      options.fetch = databricksFetch
    }
  },
})
"""

# OpenCode 2 rejects modules without a default `{ id, setup }` definition and
# has no mutable config hook, so the token is attached by session hooks.
_V2_ENTRYPOINT = """
export default {
  id: "ucode.databricks-auth",
  async setup(ctx) {
    let rejectedAuthorization
    for (const providerID of DATABRICKS_PROVIDERS) {
      await ctx.session.hook("http.request", async (event) => {
        const configured = event.request.headers.get("Authorization")
        if (!accessToken && configured?.startsWith("Bearer ")) cacheToken(configured.slice(7))
        if (!accessToken || expiresAt <= Date.now() + REFRESH_SKEW_MS) await refreshToken()
        event.request.headers.set("Authorization", "Bearer " + accessToken)
      }, { providerID })

      await ctx.session.hook("http.response", (event) => {
        if (event.response.status === 401) {
          rejectedAuthorization = event.request.headers.get("Authorization")
        }
      }, { providerID })

      // OpenCode does not retry a 401 by default; retry once with a new token.
      await ctx.session.hook("retry", async (event) => {
        if (event.error.status !== 401 || event.attempt > 2) return
        // Another concurrent request may already have refreshed this token.
        if (rejectedAuthorization === "Bearer " + accessToken) await refreshToken()
        event.decision = { retry: true, delay: 0 }
      }, { providerID })
    }
  },
}
"""


_PRELUDE = _PRELUDE_TEMPLATE.replace(
    "__PROVIDER_IDS__", "\n".join(f'  "{provider_id}",' for provider_id in PROVIDER_IDS)
)


def render_auth_plugin(state: dict, *, v2: bool) -> str:
    """Render the local plugin that refreshes Databricks auth on demand.

    `v2` selects the OpenCode 2 entrypoint. OpenCode 1 and Kilo use the other one.
    """
    argv = build_auth_token_argv(
        state["workspace"],
        state.get("profile"),
        use_pat=bool(state.get("use_pat")),
    )
    # A 401 must not return the same still-unexpired cached credential.
    argv.append("--force-refresh")
    entrypoint = _V2_ENTRYPOINT if v2 else _V1_ENTRYPOINT
    return (_PRELUDE + entrypoint).replace("__AUTH_COMMAND__", json.dumps(argv))


@dataclass(frozen=True)
class FamilySettings:
    """What differs between the agents in the checks below. Strings only, so a test that
    patches a wrapper's version, path or token still reaches the wrapper's own value."""

    display: str
    # State key that holds an admin-chosen default model; None for an agent without one.
    default_model_state_key: str | None
    # Replaces the plain hint when `opencode_models` is empty.
    empty_models_hint: str | None


def parse_version(value: str) -> tuple[int, int, int] | None:
    match = re.search(r"(\d+)\.(\d+)\.(\d+)", value)
    if match is None:
        return None
    major, minor, patch = match.groups()
    return int(major), int(minor), int(patch)


def minimum_version_message(
    settings: FamilySettings,
    installed: str,
    minimum: tuple[int, int, int],
    minimum_text: str,
) -> str | None:
    parsed = parse_version(installed)
    if parsed is None or parsed >= minimum:
        return None
    return (
        f"{settings.display} {installed} is too old. ucode requires {settings.display} "
        f"{minimum_text} or newer for renewable Databricks authentication."
    )


def minimum_version_error(message: str | None, package: str) -> str | None:
    if message is None:
        return None
    return f"{message} Update it with `npm install -g {package}`."


def resolve_model_selector(model: str, opencode_models: dict[str, list[str]]) -> str:
    """Return a model selector in provider/model form when possible."""
    if model.startswith(("databricks-anthropic/", "databricks-google/", "databricks-oss/")):
        return model

    anthropic_models = opencode_models.get("anthropic") or []
    if model in anthropic_models:
        return f"databricks-anthropic/{model}"

    gemini_models = opencode_models.get("gemini") or []
    if model in gemini_models:
        return f"databricks-google/{model}"

    oss_models = opencode_models.get("oss") or []
    if model in oss_models:
        return f"databricks-oss/{model}"

    return model


def resolve_explicit_model(settings: FamilySettings, model: str, state: dict) -> str:
    """Resolve and validate a model explicitly selected for a launch.

    Databricks model ids are exposed in family buckets in ucode state, while the agent
    addresses those models through managed provider ids. Other provider/model selectors
    belong to the agent and are passed through.
    """
    selector = model.strip()
    if not selector:
        raise RuntimeError(f"{settings.display} model must not be empty.")

    opencode_models = state.get("opencode_models") or {}
    resolved = resolve_model_selector(selector, opencode_models)
    if "/" not in selector:
        if resolved != selector:
            return resolved
        hint = (
            settings.empty_models_hint
            if settings.empty_models_hint and not opencode_models
            else "Choose a discovered model id or pass a provider/model selector."
        )
        raise RuntimeError(f"{settings.display} model '{selector}' is not configured. {hint}")

    provider, _, model_id = selector.partition("/")
    if not provider or not model_id:
        raise RuntimeError(f"{settings.display} model selector must use provider/model form.")
    if provider not in PROVIDER_IDS:
        return selector

    if resolve_model_selector(model_id, opencode_models) == selector:
        return selector
    raise RuntimeError(
        f"{settings.display} model '{selector}' is not configured for managed provider "
        f"'{provider}'."
    )


def default_model(settings: FamilySettings, state: dict) -> str | None:
    key = settings.default_model_state_key
    if key is not None and isinstance(state.get(key), str):
        return state.get(key)
    opencode_models = state.get("opencode_models") or {}
    anthropic = opencode_models.get("anthropic") or []
    if anthropic:
        return anthropic[0]
    gemini = opencode_models.get("gemini") or []
    if gemini:
        return gemini[0]
    oss = opencode_models.get("oss") or []
    return oss[0] if oss else None
