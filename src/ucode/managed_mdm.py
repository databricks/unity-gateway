"""``ug configure --global`` on a workspace that publishes an agent configuration.

An MDM policy (Jamf or similar) runs ``ug configure --global`` as root on each machine. When the
workspace publishes a Unity Gateway Agent Configuration (UGAC), the run reads it with the machine
credential and rebuilds every listed agent's machine-wide files from scratch:

- Claude Code: ``managed-settings.json`` = UG defaults < ``agent_native_settings`` < feature
  requirements < gateway requirements.
- Codex: ``/etc/codex/requirements.toml`` (enforced) = ``agent_native_requirements`` + UG's
  provider lock, and ``/etc/codex/config.toml`` (defaults) = ``agent_native_settings`` + UG's
  default model.

How UG treats each key comes from the ownership tables in :mod:`ucode.ownership`. The files hold no
per-user values: the sign-in helper runs as whichever developer starts the agent, and discovered
models stay per user. The run also saves the UGAC copy per-user runs read
(``/etc/unitygateway/managed-settings.json``) and the MDM marker
(``/etc/unitygateway/agents-state.json``). With the marker present, every other ``ug`` run leaves
the machine-wide files alone.
"""

