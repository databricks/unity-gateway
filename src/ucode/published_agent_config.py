def parse_agents(raw: str | None) -> list[str]:
    """The machine-wide agents to rebuild; all of them when ``--agents`` is omitted."""
    if not raw:
        return list(MANAGED_AGENTS)
    names = [name.strip().lower() for name in raw.split(",") if name.strip()]
    aliases = {
        "claude": "claude",
        "claude-code": "claude",
        "claude_code": "claude",
        "codex": "codex",
    }
    unknown = [name for name in names if name not in aliases]
    if unknown or not names:
        raise ManagedRunError(
            EXIT_USAGE,
            "`ug configure --global` writes machine-wide settings only for "
            f"{', '.join(MANAGED_AGENTS)}; got {', '.join(unknown) or raw}.",
        )
    return list(dict.fromkeys(aliases[name] for name in names))


def has_machine_privileges() -> bool:
    """Whether this run can write root-owned files without a password prompt."""
    if _running_as_root():
        return True
    try:
        result = subprocess_cross_os.run(
            ["/usr/bin/sudo", "-n", "true"], capture_output=True, text=True, check=False
        )
    except OSError:
        return False
    return result.returncode == 0


def check_privileges() -> None:
    """Fail with exit 3 when this run can't write root-owned files.

    An unattended run, such as an MDM policy, needs root or a working ``sudo -n``. A terminal may
    approve a sudo prompt instead."""
    if has_machine_privileges() or _sudo_may_prompt():
        return
    raise ManagedRunError(
        EXIT_PRIVILEGES,
        "`ug configure --global` writes machine-wide files. Run it as root, for example from "
        "your MDM policy, or from a terminal where you can approve the sudo prompt.",
    )


def resolve_host(workspace: str) -> tuple[str, str]:
    """The ``state.json`` key and host for ``workspace``, selecting it for this process."""
    try:
        key = resolve_workspace(workspace)
    except RuntimeError as exc:
        raise ManagedRunError(EXIT_USAGE, str(exc)) from exc
    host, workspace_id = split_workspace_key(key)
    activate(host, workspace_id)
    return key, host


def load_draft(path: str) -> dict:
    """A draft agent configuration for ``--from-file``, in the format ``ug export`` writes."""
    try:
        raw = json.loads(Path(path).expanduser().read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ManagedRunError(EXIT_USAGE, f"Could not read --from-file {path}: {exc}") from exc
    if not isinstance(raw, dict):
        raise ManagedRunError(
            EXIT_USAGE, f"--from-file {path} must hold one agent configuration object."
        )
    # `ug export` adds the source workspace and its own format version around the config.
    return {key: value for key, value in raw.items() if key != "workspace"}


class SignInUnavailable(ManagedRunError):
    """No credential for the workspace yet; ``ug configure --global`` may sign in and merge."""


def sign_in(host: str, profile: str | None) -> str:
    """A token for ``host`` without signing anyone in. Raises :class:`SignInUnavailable`."""
    try:
        return get_databricks_token(host, profile)
    except (RuntimeError, OSError) as exc:
        raise SignInUnavailable(EXIT_FETCH, f"Could not authenticate to {host}: {exc}") from exc


def fetch_published(host: str, token: str) -> dict | None:
    """The workspace's published agent configuration, or None when it publishes none.

    Coding agent configs being turned off counts as none. Raises :class:`ManagedRunError` (exit 4)
    when the read fails.
    """
    raw, reason = get_managed_config(host, token)
    if reason is not None:
        if _is_feature_disabled(reason):
            return None
        raise ManagedRunError(EXIT_FETCH, f"Could not read the agent configuration: {reason}")
    return raw


def no_config_error(host: str) -> ManagedRunError:
    return ManagedRunError(
        EXIT_NO_CONFIG,
        f"{host} publishes no coding agent configuration, or coding agent configs are turned off. "
        "This machine's settings are managed from it, so nothing was written. To remove Unity "
        "Gateway's settings from this machine, run `ug revert` as root.",
    )


# What a run does to one file, decided before it writes anything.
CREATE = "create"
REPLACE = "replace"
REMOVE = "remove"
UNCHANGED = "unchanged"


def file_action(path: Path, text: str | None) -> str:
    try:
        current = read_managed_file(path)
    except RuntimeError:
        current = ""  # Unreadable here, so assume it differs.
    if text is None:
        return REMOVE if current is not None else UNCHANGED
    if current is None:
        return CREATE
    return UNCHANGED if current == text else REPLACE


def _saved_config_action(key: str, raw: dict) -> str:
    """What :func:`save_managed_state` does to the saved agent configuration."""
    path = managed_files.UNITY_GATEWAY_MANAGED_SETTINGS_PATH
    try:
        current = read_managed_file(path)
    except RuntimeError:
        return REPLACE
    if current is None:
        return CREATE
    try:
        existing = json.loads(current)
    except ValueError:
        return REPLACE
    config = existing.get("config") if isinstance(existing, dict) else None
    workspace = existing.get("workspace") if isinstance(existing, dict) else None
    if (
        isinstance(config, dict)
        and isinstance(workspace, str)
        and normalize_workspace_url(workspace) == normalize_workspace_url(key)
        and _policy_content(config) == _policy_content(raw)
    ):
        return UNCHANGED
    return REPLACE


def print_file_actions(actions: dict[Path, str], *, dry_run: bool) -> None:
    """One line per file the run touches: create, replace, remove, or unchanged."""
    console.print(f"[bold]{'Files this run would change' if dry_run else 'Files'}[/bold]")
    width = max(len(action) for action in actions.values())
    for path, action in actions.items():
        console.print(f"  {action:<{width}}  {escape(str(path))}", soft_wrap=True)
    console.print()


def print_report(plans: list[AgentPlan], *, dry_run: bool) -> None:
    for plan in plans:
        verb = plan.outcome
        if plan.outcome == "written" and dry_run:
            verb = "would write"
        elif plan.outcome == "dropped" and dry_run:
            verb = "would drop"
        console.print(f"[bold]{escape(plan.display)}[/bold]: {escape(verb)}")
        if plan.outcome == "dropped":
            console.print(
                "  Not enabled in the agent configuration, so its machine-wide files are removed."
            )
        for path, composed in plan.reports:
            if not composed.items:
                continue
            console.print(f"  {escape(str(path))}", soft_wrap=True)
            for item in composed.items:
                note = f" — {item.note}" if item.note and item.outcome != ownership.APPLIED else ""
                console.print(
                    f"    {escape(f'[{item.outcome}]')} {escape(item.path)}{escape(note)}",
                    soft_wrap=True,
                )
        for warning in plan.warnings:
            print_warning(f"{plan.display}: {warning}")


def _write_files(plans: list[AgentPlan]) -> None:
    for plan in plans:
        if not plan.files:
            continue
        try:
            reconcile_privileged_files(plan.files, display=plan.display)
        except (OSError, RuntimeError, subprocess.CalledProcessError) as exc:
            raise ManagedRunError(
                EXIT_WRITE, f"Could not write {plan.display}'s files: {exc}"
            ) from exc
        for path, text in plan.files.items():
            if read_managed_file(path) != text:
                raise FileChangedDuringWrite(path)


def _next_state(workspace: str, plans: list[AgentPlan], previous: dict | None) -> dict:
    agents = dict((previous or {}).get("agents") or {})
    for plan in plans:
        if plan.outcome == "written":
            agents[plan.agent] = {"paths": [str(path) for path in agent_paths(plan.agent)]}
        else:
            agents.pop(plan.agent, None)
    return {
        "version": MARKER_VERSION,
        "workspace": workspace,
        "ug_version": ug_version(),
        "agents": agents,
    }


def run(
    *,
    key: str,
    raw: dict,
    agents: list[str],
    dry_run: bool,
    source: str | None = None,
    profile: str | None = None,
    token: str | None = None,
) -> None:
    """Rebuild ``agents``' machine-wide files from ``raw``.

    ``source`` names a draft file being previewed. ``token`` (else ``profile``) is the run's sign-in,
    which also lists the MCP servers in a Unity Catalog location. Raises :class:`ManagedRunError` on failure; nothing is
    written unless every file could be built.
    """
    from ucode import mcp

    host = split_workspace_key(key)[0]
    manifest = normalize_managed_config(raw)
    errors = validate_manifest(manifest, None)
    if errors and source:
        detail = "\n".join(f"  - {error}" for error in errors)
        raise ManagedRunError(
            EXIT_USAGE, f"The agent configuration in {source} isn't valid:\n{detail}"
        )
    for error in errors:
        print_warning(f"Agent configuration: {error}")

    previous = published_agent_config_marker()
    if previous is not None and previous.get("workspace") != key:
        skipped = [agent for agent in MANAGED_AGENTS if agent not in agents]
        if skipped:
            # Agents left out would keep routing to the old workspace.
            print_note(
                f"The workspace changed from {previous.get('workspace')} to {key}, so every agent "
                f"is rebuilt, including {', '.join(skipped)}."
            )
            agents = list(MANAGED_AGENTS)

    enabled = manifest.get("enabled_agents") or {}
    if token is not None:
        _reject_relayed_services(manifest, [a for a in agents if a in enabled], host, token)
    mcp_entries: dict[str, dict[str, dict]] = {"claude": {}, "codex": {}}
    claude_mcp_names: set[str] = set()
    if any(agent in enabled for agent in agents):
        try:
            mcp_entries, claude_mcp_names = mcp.resolve_machine_mcp_entries(
                manifest, host, profile=profile, token=token
            )
        except RuntimeError as exc:
            raise ManagedRunError(EXIT_FETCH, f"Could not resolve the MCP servers: {exc}") from exc

    try:
        plans = plan_agents(
            manifest, host, agents, mcp_entries, previous, claude_mcp_names=claude_mcp_names
        )
    except ValueError as exc:
        raise ManagedRunError(EXIT_USAGE, str(exc)) from exc

    marker_path = managed_files.PUBLISHED_AGENT_CONFIG_MARKER_PATH
    marker_text = json.dumps(_next_state(key, plans, previous), indent=2, sort_keys=True) + "\n"
    actions = {path: file_action(path, text) for plan in plans for path, text in plan.files.items()}
    actions[managed_files.UNITY_GATEWAY_MANAGED_SETTINGS_PATH] = _saved_config_action(key, raw)
    actions[marker_path] = file_action(marker_path, marker_text)

    if dry_run:
        print_file_actions(actions, dry_run=True)
        for plan in plans:
            for path, text in plan.files.items():
                action = actions[path]
                console.print(f"[bold]\\[dry run] {action} {escape(str(path))}[/bold]")
                if action in (CREATE, REPLACE) and text is not None:
                    console.print(escape(text), highlight=False, soft_wrap=True)
                console.print()
        print_report(plans, dry_run=True)
        return

    # Each file is replaced atomically. Keep the previous contents so that a failure partway
    # through restores every file, and the machine never mixes two runs' files.
    snapshot = _snapshot(actions)
    try:
        _write_files(plans)
        try:
            save_managed_state(key, raw, allow_sudo=True, sets_machine_workspace=True)
            reconcile_privileged_files({marker_path: marker_text}, display="Unity Gateway")
        except (
            ManagedFileWriteUnavailable,
            RuntimeError,
            OSError,
            subprocess.CalledProcessError,
        ) as exc:
            raise ManagedRunError(
                EXIT_WRITE,
                f"Could not save the published agent configuration's marker file: {exc}",
            ) from exc
    except FileChangedDuringWrite as exc:
        # Keep the other writer's file; restore the rest so the machine doesn't mix two runs.
        _restore({path: text for path, text in snapshot.items() if path != exc.path})
        raise
    except ManagedRunError:
        _restore(snapshot)
        raise
    except (RuntimeError, OSError, subprocess.CalledProcessError) as exc:
        _restore(snapshot)
        raise ManagedRunError(EXIT_WRITE, f"Could not write the machine-wide files: {exc}") from exc
    except KeyboardInterrupt:
        _restore(snapshot)
        raise
    print_file_actions(actions, dry_run=False)
    print_report(plans, dry_run=False)


def _reject_relayed_services(manifest: dict, agents: list[str], host: str, token: str) -> None:
    """Refuse a model provider service that relays a subscription: each developer signs in to it
    through a local proxy, which machine-wide files can't express."""
    for agent in agents:
        service_name = managed_provider_service(manifest, agent)
        if not service_name:
            continue
        service, _reason = get_model_provider_service(service_name, host, token)
        if service is not None and service.get("relayed"):
            raise ManagedRunError(
                EXIT_USAGE,
                f"Model provider service '{service_name}' relays a subscription, which each "
                "developer signs in to themselves, so `ug configure --global` can't write it "
                "machine-wide. Use a model provider service with an API key, or have developers "
                "run `ug configure`.",
            )


def _snapshot(actions: dict[Path, str]) -> dict[Path, str | None]:
    """The current contents of every file the run changes."""
    snapshot: dict[Path, str | None] = {}
    for path, action in actions.items():
        if action == UNCHANGED:
            continue
        try:
            snapshot[path] = read_managed_file(path)
        except RuntimeError as exc:
            raise ManagedRunError(EXIT_WRITE, f"Could not back up {path}: {exc}") from exc
    return snapshot


def _restore(snapshot: dict[Path, str | None]) -> None:
    try:
        reconcile_privileged_files(snapshot, display="Unity Gateway")
    except (OSError, RuntimeError, subprocess.CalledProcessError) as exc:
        print_warning(
            f"Could not restore the previous machine-wide files: {exc} "
            "Run `ug configure --global` again."
        )


def revert_machine() -> list[str]:
    """Remove every machine-wide file a managed run wrote, the saved agent configuration, and the
    marker file. Returns the removed paths.

    Needs root, ``sudo -n``, or a terminal that can approve sudo; raises :class:`ManagedRunError` with
    exit 3 otherwise.
    """
    state = published_agent_config_marker()
    if state is None:
        return []
    check_privileges()
    files: dict[Path, str | None] = {}
    for info in (state.get("agents") or {}).values():
        for raw_path in (info or {}).get("paths") or []:
            files[Path(raw_path)] = None
    files[managed_files.UNITY_GATEWAY_MANAGED_SETTINGS_PATH] = None
    # Last, so a failed revert leaves the marker and the next revert retries.
    files[managed_files.PUBLISHED_AGENT_CONFIG_MARKER_PATH] = None
    existing = [path for path in files if path.exists()]
    reconcile_privileged_files(files, display="Unity Gateway")
    return [str(path) for path in existing]
