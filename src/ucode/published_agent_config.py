MANAGED_AGENTS = ("claude", "codex")
MARKER_VERSION = 1
LEGACY_CODEX_MANAGED_CONFIG_PATH = Path("/etc/codex/managed_config.toml")
CODEX_FILE_HEADER = (
    "# Generated by Unity Gateway (`ug configure --global`) from your workspace's\n"
    "# agent configuration. It is rebuilt on every managed run, so edits here are lost.\n\n"
)

EXIT_OK = 0
EXIT_USAGE = 2
EXIT_PRIVILEGES = 3
EXIT_FETCH = 4
EXIT_NO_CONFIG = 5
EXIT_WRITE = 6


class ManagedRunError(RuntimeError):
    """A managed run failure carrying the documented exit code."""

    def __init__(self, code: int, message: str) -> None:
        super().__init__(message)
        self.code = code


class FileChangedDuringWrite(ManagedRunError):
    """Another writer replaced ``path`` during the run, so the run must not restore over it."""

    def __init__(self, path: Path) -> None:
        super().__init__(
            EXIT_WRITE,
            f"{path} changed while it was being written. Run `ug configure --global` again.",
        )
        self.path = path


@dataclass
class AgentPlan:
    """What one agent's machine-wide files become this run."""

    agent: str
    display: str
    outcome: str  # "written" | "dropped" | "not enabled"
    files: dict[Path, str | None] = field(default_factory=dict)
    # The admin's keys in each file, and what happened to each.
    reports: list[tuple[Path, ownership.Composed]] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


