"""``ug configure --global`` on a workspace that publishes an agent configuration.

A managed run is ``ug configure --global`` on a workspace that publishes a Unity Gateway Agent
Configuration (UGAC). It runs as root, often from an MDM policy, a provisioning script, or a fleet
tool. The run reads the UGAC and rebuilds every listed agent's machine-wide files from scratch. Each file layers the
admin's native fields under what UG requires; ``build_<agent>`` defines the files for one agent,
and ``MANAGED_AGENTS`` lists the agents supported so far.

How UG treats each key comes from the agent's ownership table in :mod:`ucode.ownership`. The files hold no
per-user values: the sign-in helper runs as whichever developer starts the agent, and discovered
models stay per user. The run also saves the UGAC copy per-user runs read
(``/etc/unitygateway/managed-settings.json``) and the marker file
(``/etc/unitygateway/agents-state.json``). With the marker present, every other ``ug`` run leaves
the machine-wide files alone.
"""

