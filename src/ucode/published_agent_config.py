def agent_features(manifest: dict, tool: str) -> set[str]:
    """The UG features the agent config turns on for ``tool``."""
    entry = (manifest.get("enabled_agents") or {}).get(tool) or {}
    features: set[str] = set()
    if managed_otel_tracing_enabled(manifest, tool):
        features.add("tracing")
    if entry.get("smart_routing_enabled") is True:
        features.add("smart_routing")
    model_config = entry.get("model_config") or {}
    if any(
        model_config.get(key)
        for key in ("model_services", "unity_catalog_location", "model_provider_service")
    ):
        features.add("models")
    return features


def _agent_entry(manifest: dict, tool: str) -> dict:
    entry = (manifest.get("enabled_agents") or {}).get(tool)
    return entry if isinstance(entry, dict) else {}


def _native(entry: dict, variant: str, field: str) -> dict | None:
    """``field`` of the entry's ``agent_native_config`` variant, e.g. ``codex.requirements``."""
    value = (entry.get(variant) or {}).get(field)
    return value if isinstance(value, dict) else None


def _http_headers(manifest: dict, tool: str) -> dict[str, str] | None:
    headers = _agent_entry(manifest, tool).get("http_headers")
    return headers if isinstance(headers, dict) and headers else None


def claude_family_pins(manifest: dict) -> dict[str, str]:
    """Family default models: pinned in ``default_models``, else the newest in an explicit list."""
    pins = dict(managed_claude_family_models(manifest) or {})
    static = managed_static_models(manifest, "claude") or []
    for family, candidates in claude_family_candidates(static).items():
        if candidates:
            pins.setdefault(family, candidates[0])
    return pins


def claude_ug_values(
    manifest: dict, workspace: str, mcp_entries: dict[str, dict] | None = None
) -> dict:
    """Everything UG writes into Claude's managed file: gateway and feature requirements.

    UG defaults are not included; they come from the ownership table.
    """
    provider = managed_provider_service(manifest, "claude")
    location = None if provider else managed_unity_catalog_location(manifest, "claude")
    pins = claude_family_pins(manifest)
    overlay, _keys = claude_agent.render_overlay(
        workspace,
        None,
        claude_models=pins if not provider else None,
        # The gateway rejects Claude's hosted search, so its built-in tool is always denied.
        disable_web_search=True,
        profile=None,
        provider=provider,
        provider_models=pins if provider else None,
        parent_schema=location,
        static_models=managed_static_models(manifest, "claude"),
        otel_tracing=managed_otel_tracing_enabled(manifest, "claude"),
        managed_http_headers=_http_headers(manifest, "claude"),
    )
    env = overlay["env"]
    # These are UG defaults the admin may override; the table supplies their values.
    for entry in ownership.entries_by_class(
        ownership.load_table("claude").section("managed_settings"), "default"
    ):
        if entry.path[0] == "env":
            env.pop(entry.path[1], None)
    # Set per launch (smart routing), never in the managed file.
    env.pop("ANTHROPIC_MODEL", None)
    # Blank provider switches keep developers from routing around the gateway.
    env["CLAUDE_CODE_USE_BEDROCK"] = ""
    env["CLAUDE_CODE_USE_VERTEX"] = ""
    if mcp_entries:
        overlay[claude_agent.MANAGED_MCP_SETTINGS_KEY] = dict(mcp_entries)
    return overlay


def claude_native_settings(entry: dict) -> dict | None:
    """The admin's Claude Code settings: ``agent_native_settings`` and
    ``claude_code.managed_settings``. The server accepts only one per entry; if both arrive, the
    newer field wins key by key."""
    legacy = entry.get("agent_native_settings")
    current = _native(entry, "claude_code", "managed_settings")
    if not isinstance(current, dict):
        return legacy if isinstance(legacy, dict) else None
    if not isinstance(legacy, dict):
        return current
    return deep_merge_dict(copy.deepcopy(legacy), current)


def build_claude(
    manifest: dict,
    workspace: str,
    mcp_entries: dict[str, dict] | None = None,
    mcp_names: set[str] | None = None,
) -> ownership.Composed:
    """``mcp_names`` are the MCP servers ug registers for Claude anywhere, which an admin's
    ``allowedMcpServers`` must admit."""
    native = claude_native_settings(_agent_entry(manifest, "claude"))
    ug_values = claude_ug_values(manifest, workspace, mcp_entries)
    allowlist = (native or {}).get(claude_agent.CLAUDE_ALLOWED_MCP_SERVERS_KEY)
    if isinstance(allowlist, list):
        # Claude Code blocks a server missing from the allowlist, and admins can't be expected to
        # know the names ug registers, so ug adds them. Without an admin allowlist, ug adds none.
        names = {*(mcp_entries or {}), *(mcp_names or ()), claude_agent.WEB_SEARCH_MCP_NAME}
        ug_values[claude_agent.CLAUDE_ALLOWED_MCP_SERVERS_KEY] = [
            {"serverName": name} for name in sorted(names)
        ]
    return ownership.compose(
        ownership.load_table("claude").section("managed_settings"),
        native=native,
        ug_values=ug_values,
        features=agent_features(manifest, "claude"),
    )


def _codex_identity(entry: dict) -> dict:
    """The requirements allowlist identity for one of UG's Codex MCP entries."""
    if isinstance(entry.get("url"), str):
        return {"url": entry["url"]}
    return {"command": entry.get("command")}


def codex_requirements_ug_values(
    manifest: dict, workspace: str, mcp_entries: dict[str, dict] | None = None
) -> dict:
    overlay = codex_agent.render_overlay(
        workspace, managed_http_headers=_http_headers(manifest, "codex")
    )
    provider = overlay["model_providers"][codex_agent.CODEX_MODEL_PROVIDER_NAME]
    routing = codex_agent._LAUNCH_ROUTING_HEADER_ENV_VARS
    # Per-launch headers ride in environment variables `ug codex` sets: the locked provider entry
    # replaces anything a launch passes with `-c`.
    provider["http_headers"] = {
        name: value
        for name, value in provider["http_headers"].items()
        if name.casefold() not in {header.casefold() for header in routing}
    }
    provider["env_http_headers"] = dict(routing)
    values: dict = {
        "model_provider": overlay["model_provider"],
        "model_providers": {codex_agent.CODEX_MODEL_PROVIDER_NAME: provider},
    }
    native = _native(_agent_entry(manifest, "codex"), "codex", "requirements")
    allowlist = native.get("mcp_servers") if isinstance(native, dict) else None
    if isinstance(allowlist, dict) and mcp_entries:
        # Only an admin allowlist limits MCP servers; add UG's so it doesn't block them.
        values["mcp_servers"] = {
            name: {"identity": _codex_identity(entry)} for name, entry in mcp_entries.items()
        }
    return values


def build_codex(
    manifest: dict, workspace: str, mcp_entries: dict[str, dict] | None = None
) -> tuple[ownership.Composed, ownership.Composed]:
    table = ownership.load_table("codex")
    entry = _agent_entry(manifest, "codex")
    features = agent_features(manifest, "codex")
    names: dict[tuple[str, ...], set[str]] = {("mcp_servers",): set(mcp_entries or {})}
    requirements = ownership.compose(
        table.section("requirements"),
        native=_native(entry, "codex", "requirements"),
        ug_values=codex_requirements_ug_values(manifest, workspace, mcp_entries),
        features=features,
        ug_table_names=names,
    )
    default_model = managed_default_model(manifest, "codex")
    settings = ownership.compose(
        table.section("config"),
        native=_native(entry, "codex", "config"),
        ug_values={"model": default_model} if default_model else {},
        features=features,
        ug_table_names=names,
    )
    return requirements, settings


def _strip_nulls(doc: dict, prefix: tuple[str, ...] = ()) -> list[str]:
    """Remove ``null`` values, which TOML can't hold; returns their dotted paths."""
    removed: list[str] = []
    for key in list(doc):
        value = doc[key]
        if value is None:
            del doc[key]
            removed.append(".".join((*prefix, key)))
        elif isinstance(value, dict):
            removed += _strip_nulls(value, (*prefix, key))
        elif isinstance(value, list) and any(item is None for item in value):
            doc[key] = [item for item in value if item is not None]
            removed.append(".".join((*prefix, key)))
    return removed


def dump_codex(doc: dict) -> str:
    return CODEX_FILE_HEADER + tomlkit.dumps(doc)


def _ug_wrote_legacy_codex_file() -> bool:
    """Whether ``managed_config.toml`` holds a provider an earlier ``ug configure`` wrote."""
    text = read_managed_file(LEGACY_CODEX_MANAGED_CONFIG_PATH)
    if text is None:
        return False
    try:
        doc = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return False
    return doc.get("model_provider") == codex_agent.CODEX_MODEL_PROVIDER_NAME


def agent_paths(agent: str) -> list[Path]:
    if agent == "claude":
        path = claude_agent.managed_settings_path()
        return [path] if path is not None else []
    return [managed_files.CODEX_SYSTEM_REQUIREMENTS_PATH, managed_files.CODEX_SYSTEM_CONFIG_PATH]


def plan_agents(
    manifest: dict,
    workspace: str,
    agents: list[str],
    mcp_entries: dict[str, dict[str, dict]],
    previous_state: dict | None,
    *,
    claude_mcp_names: set[str] | None = None,
) -> list[AgentPlan]:
    previously_written = set(((previous_state or {}).get("agents") or {}).keys())
    enabled = manifest.get("enabled_agents") or {}
    plans: list[AgentPlan] = []
    for agent in agents:
        display = "Claude Code" if agent == "claude" else "Codex"
        if agent not in enabled:
            if agent in previously_written:
                plan = AgentPlan(agent, display, "dropped")
                plan.files = dict.fromkeys(agent_paths(agent))
            else:
                plan = AgentPlan(agent, display, "not enabled")
            plans.append(plan)
            continue
        plan = AgentPlan(agent, display, "written")
        if agent == "claude":
            if not agent_paths("claude"):
                raise ManagedRunError(
                    EXIT_USAGE, "This platform has no machine-wide Claude Code settings file."
                )
            composed = build_claude(
                manifest, workspace, mcp_entries.get("claude"), claude_mcp_names
            )
            path = agent_paths("claude")[0]
            plan.files[path] = claude_agent._dump_managed_settings(composed.doc)
            plan.reports.append((path, composed))
            tracing_paths = {
                entry.dotted
                for entry in ownership.load_table("claude").section("managed_settings")
                if entry.feature == "tracing"
            }
            if "tracing" in agent_features(manifest, "claude") and any(
                item.outcome == ownership.SKIPPED and item.path in tracing_paths
                for item in composed.items
            ):
                plan.warnings.append(
                    "Tracing is on, so Unity Gateway's trace settings and otelHeadersHelper "
                    "replace your own OTEL export settings."
                )
        else:
            requirements, settings = build_codex(manifest, workspace, mcp_entries.get("codex"))
            for composed, path in (
                (requirements, managed_files.CODEX_SYSTEM_REQUIREMENTS_PATH),
                (settings, managed_files.CODEX_SYSTEM_CONFIG_PATH),
            ):
                for dotted in _strip_nulls(composed.doc):
                    composed.items.append(
                        ownership.ReportItem(ownership.SKIPPED, dotted, "TOML has no null value.")
                    )
                plan.files[path] = dump_codex(composed.doc)
                plan.reports.append((path, composed))
            if _ug_wrote_legacy_codex_file():
                plan.files[LEGACY_CODEX_MANAGED_CONFIG_PATH] = None
                plan.warnings.append(
                    f"Removed {LEGACY_CODEX_MANAGED_CONFIG_PATH}, which an earlier `ug configure` "
                    "wrote: its values would outrank `ug codex`'s launch settings."
                )
            version_warning = _codex_version_warning()
            if version_warning:
                plan.warnings.append(version_warning)
        plans.append(plan)
    return plans


def _codex_version_warning() -> str | None:
    version = agent_version("codex")
    parsed = codex_agent._parse_version(version)
    if parsed is None or parsed >= codex_agent.MINIMUM_CODEX_VERSION:
        return None
    return (
        f"Codex {version} is installed, but the provider lock in requirements.toml needs Codex "
        f"{codex_agent.MINIMUM_CODEX_VERSION_TEXT} or newer. Update Codex on this machine."
    )


