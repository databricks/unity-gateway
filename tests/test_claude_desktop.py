def test_configure_leaves_unrelated_and_old_generated_profiles_untouched(tmp_path, directory):
    prior = _seed_metadata(directory, name="Unity Gateway")
    old_id = _uuid()
    old_path = directory / f"{old_id}.json"
    _write_json(old_path, {"legacy": True})
    metadata = _read(directory / desktop.META_FILENAME)
    metadata["entries"].append({"id": old_id, "name": "Unity Gateway", "extra": "keep"})
    metadata["extra"] = {"keep": True}
    _write_json(directory / desktop.META_FILENAME, metadata)
    files_before = {path.name: path.read_bytes() for path in directory.iterdir()}
    state_path = tmp_path / "state.json"
    result = _configure(state_path)
    assert _read(result.metadata_path)["entries"][:-1] == metadata["entries"]
    assert _read(result.metadata_path)["extra"] == {"keep": True}
    desktop.revert_claude_desktop(state_path=state_path)
    assert _read(result.metadata_path) == metadata
    assert _read(result.metadata_path)["appliedId"] == prior
    for name, contents in files_before.items():
        if name != desktop.META_FILENAME:
            assert (directory / name).read_bytes() == contents


