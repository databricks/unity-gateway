@pytest.mark.parametrize("deleted", ["profile", "entry", "both", "metadata"])
def test_configure_recreates_deleted_profile_and_registration(tmp_path, directory, deleted):
    prior = _seed_metadata(directory)
    state_path = tmp_path / "state.json"
    result = _configure(state_path)
    if deleted in ("profile", "both"):
        result.profile_path.unlink()
    if deleted == "metadata":
        result.metadata_path.unlink()
    elif deleted in ("entry", "both"):
        metadata = _read(result.metadata_path)
        metadata["entries"] = [entry for entry in metadata["entries"] if entry["id"] == prior]
        _write_json(result.metadata_path, metadata)
    _configure(state_path)
    assert result.profile_path.is_file()
    metadata = _read(result.metadata_path)
    assert metadata["appliedId"] == desktop.PROFILE_ID
    assert sum(entry["id"] == desktop.PROFILE_ID for entry in metadata["entries"]) == 1
    desktop.revert_claude_desktop(state_path=state_path)
    assert not result.profile_path.exists()
    assert all(
        entry["id"] != desktop.PROFILE_ID for entry in _read(result.metadata_path)["entries"]
    )


