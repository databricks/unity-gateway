@pytest.mark.parametrize("operation", ["configure", "revert"])
@pytest.mark.parametrize("failed_file", ["profile", "metadata", "state"])
@pytest.mark.parametrize("existing", ["absent", "unrecorded", "configured"])
def test_write_failure_rolls_back_exact_bytes(
    tmp_path, directory, monkeypatch, operation, failed_file, existing
):
    _seed_metadata(directory)
    state_path = tmp_path / "state.json"
    profile_path = directory / f"{desktop.PROFILE_ID}.json"
    if existing == "unrecorded":
        profile_path.write_bytes(b"{malformed original\\xff")
    elif existing == "configured":
        _configure(state_path)
    if operation == "revert":
        _configure(state_path)
        profile_path.write_bytes(b"{malformed original\\xff")
    if operation == "configure" and existing == "configured":
        metadata = _read(directory / desktop.META_FILENAME)
        metadata.pop("appliedId")
        _write_json(directory / desktop.META_FILENAME, metadata)
    before = {p.name: p.read_bytes() for p in directory.iterdir()}
    state_before = state_path.read_bytes() if state_path.exists() else None
    targets = {
        "profile": profile_path,
        "metadata": directory / desktop.META_FILENAME,
        "state": state_path,
    }
    write = desktop_config._write_or_remove
    failed = False

    def fail_once(path, payload):
        nonlocal failed
        if path == targets[failed_file] and not failed:
            failed = True
            raise OSError("simulated write failure")
        write(path, payload)

    monkeypatch.setattr(desktop_config, "_write_or_remove", fail_once)
    with pytest.raises(desktop.ClaudeDesktopError, match="rolled back"):
        if operation == "configure":
            _configure(state_path, models=("new-model",), profile_key="updated")
        else:
            desktop.revert_claude_desktop(state_path=state_path)
    assert failed
    assert {p.name: p.read_bytes() for p in directory.iterdir()} == before
    assert (state_path.read_bytes() if state_path.exists() else None) == state_before


